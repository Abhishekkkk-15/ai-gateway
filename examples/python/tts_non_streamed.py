#!/usr/bin/env python3
"""
AI Gateway Example: Non-Streamed Text-to-Speech (Python)

Demonstrates generating speech audio via the standard OpenAI audio speech API.
The gateway forwards the request to ElevenLabs (or configured provider) and writes
the complete audio file to disk using response.write_to_file().

Note on Voices:
    - ElevenLabs Default Premade (Free tier supported): 'JBFqnCBsd6RMkjVDRZzb' (George), '21m00Tcm4TlvDq8ikWAM' (Rachel)
    - OpenAI standard voices: 'alloy', 'echo', 'fable', 'onyx', 'nova', 'shimmer'

Usage:
    python examples/python/tts_non_streamed.py
"""

import os
import time
from openai import OpenAI

base_url = os.environ.get("GATEWAY_BASE_URL", "http://localhost:3000/v1")
api_key = os.environ.get("GATEWAY_API_KEY", "sk-gw-test-key")
# Model can be 'eleven_flash_v2_5', 'eleven_multilingual_v2', or 'tts-1'
model = os.environ.get("GATEWAY_TTS_MODEL", "eleven_flash_v2_5")
# Default premade voice (Free tier supported): George (JBFqnCBsd6RMkjVDRZzb)
voice = os.environ.get("GATEWAY_TTS_VOICE", "JBFqnCBsd6RMkjVDRZzb")

client = OpenAI(
    base_url=base_url,
    api_key=api_key,
)

def main():
    text_input = (
        "Hello from Python! This audio was generated by the AI Gateway through the OpenAI audio speech API."
    )
    output_file = "speech-python-non-streamed.mp3"

    print(f"[AI Gateway] Connecting to: {base_url}")
    print(f"[AI Gateway] TTS Model: {model} | Voice ID: {voice}")
    print(f'[Input Text]: "{text_input}"')
    print("--- Requesting Full Audio Speech Synthesis ---\n")

    start_time = time.time()

    try:
        response = client.audio.speech.create(
            model=model,
            voice=voice,
            input=text_input,
        )

        response.write_to_file(output_file)

        duration_ms = int((time.time() - start_time) * 1000)
        file_size_kb = os.path.getsize(output_file) / 1024

        print("[Success] Audio speech file created!")
        print(f"Output File: {os.path.abspath(output_file)}")
        print(f"File Size: {file_size_kb:.2f} KB")
        print(f"Total Latency: {duration_ms}ms")

    except Exception as e:
        print(f"[Error]: {e}")

if __name__ == "__main__":
    main()
